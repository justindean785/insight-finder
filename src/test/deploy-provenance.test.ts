/**
 * Narrow a parse result the fixtures guarantee is well-formed. The casts are
 * explicit rather than relying on discriminant narrowing: this project compiles
 * with `strict: false`, which disables narrowing on a boolean literal
 * discriminant, so `if (!parsed.ok)` does not refine the union here.
 */
const okHealth = (body: unknown): LiveHealthOk => {
  const parsed = parseHealth(body);
  if (!parsed.ok) {
    throw new Error(`fixture should parse: ${(parsed as LiveHealthFailed).reason}`);
  }
  return parsed as LiveHealthOk;
};

const buildInfo = (marker: string, committedAt = "2026-08-10T06:31:35-07:00") =>
  `// AUTO-GENERATED by scripts/stamp-build.mjs — do not edit by hand.
export const BUILD_MARKER = "${marker}";
export const BUILD_COMMITTED_AT = "${committedAt}";
`;

const liveHealth = {
  ok: true,
  service: "osint-agent",
  build: "e7e3f80",
  build_committed_at: "2026-08-10T06:31:35-07:00",
  reveal_breach_data: true,
};

describe("parseHealth", () => {
  it("reads the build pair and the reveal policy", () => {
    const parsed = okHealth(liveHealth);
    expect(parsed.ok).toBe(true);
    expect(parsed.build).toBe("e7e3f80");
    expect(parsed.committedAt).toBe("2026-08-10T06:31:35-07:00");
    expect(parsed.revealBreachData).toBe(true);
  });

  it("does not throw on the states a health endpoint actually reaches", () => {
    // Down, unauthenticated, and pre-marker builds are all expected — each must
    // come back as a reason string, because a crash here reads as a failed
    // deploy when it is a failed *check*.
    expect(parseHealth(null).ok).toBe(false);
    expect(parseHealth("<html>502</html>").ok).toBe(false);
    expect(parseHealth({ ok: false, error: "unauthorized" }).ok).toBe(false);
    expect(parseHealth({ ok: true, service: "osint-agent" }).ok).toBe(false);
  });

  it("rejects a build field that is not a SHA", () => {
    // A marker of "dev", "local", or "" would otherwise sail through and get
    // recorded as a verified production deploy.
    for (const build of ["", "dev", "local build", "HEAD", "zzzzzzz", "e7e"]) {
      expect(parseHealth({ ...liveHealth, build }).ok, `build=${JSON.stringify(build)}`).toBe(false);
    }
  });

  it("treats a missing reveal_breach_data as unknown, not as false", () => {
    // The field only shipped in #441. An older live build genuinely does not say,
    // and recording `false` would assert a policy nobody set.
    const { build_committed_at, reveal_breach_data, ...older } = liveHealth;
    expect(okHealth({ ...older, build_committed_at }).revealBreachData).toBeNull();
  });
});

describe("parseBuildInfo", () => {
  it("extracts both constants", () => {
    const parsed = parseBuildInfo(buildInfo("e7e3f80"));
    expect(parsed).toMatchObject({ ok: true, marker: "e7e3f80", committedAt: "2026-08-10T06:31:35-07:00" });
  });

  it("fails closed when the marker is absent", () => {
    expect(parseBuildInfo("export const SOMETHING_ELSE = 1;").ok).toBe(false);
    expect(parseBuildInfo(null).ok).toBe(false);
  });
});

describe("verifyDeployedCommit", () => {
  const live = okHealth(liveHealth);
  // The real shape from 2026-08-10: marker e7e3f80 (#443's squash merge), stamped
  // into build-info.ts by the NEXT commit, 2ebd330, whose parent is e7e3f80.
  const healthy: RepoFacts = {
    exists: true,
    stampCommit: "2ebd33002d17440a60ec86e25756f7a0700545f2",
    stampParent: "e7e3f8098407557e427376029645633507962979",
    onMain: true,
    buildInfoSource: buildInfo("e7e3f80"),
    sourceTreeDigest: "a1b2c3d4e5f60718293a4b5c6d7e8f9012345678",
  };

  it("verifies across the one-commit stamp offset", () => {
    // The first version of this check compared the marker against build-info.ts
    // AT the marker commit and failed a perfectly good deploy, because at that
    // commit the file still holds the PREVIOUS marker. A commit's SHA cannot be
    // known before the commit exists, so the offset is inherent — never a bug to
    // "fix" in stamp-build.mjs.
    const verdict = verifyDeployedCommit({ live, repo: healthy });
    expect(verdict.markerProvenanceOk).toBe(true);
    expect(verdict.problems).toEqual([]);
    expect(verdict.warnings).toEqual([]);
  });

  it("refuses a SHA this repository has never seen", () => {
    const verdict = verifyDeployedCommit({
      live,
      repo: { exists: false, stampCommit: null, stampParent: null, onMain: null, buildInfoSource: null },
    });
    expect(verdict.markerProvenanceOk).toBe(false);
    expect(verdict.problems[0].code).toBe("unknown_commit");
  });

  it("refuses a marker no commit here ever set", () => {
    // The SHA is real but nothing ever stamped it — the value was invented
    // rather than produced by stamp-build.mjs.
    const verdict = verifyDeployedCommit({
      live,
      repo: { ...healthy, stampCommit: null, stampParent: null, buildInfoSource: null },
    });
    expect(verdict.markerProvenanceOk).toBe(false);
    expect(verdict.problems[0].code).toBe("unstamped_marker");
  });

  it("catches a stamp commit that does not sit on the marker it names", () => {
    // The load-bearing case: the marker is a string the deployed code reports
    // about ITSELF, and a third party runs the deploy. Pinning the stamp commit
    // to the marker's position in history is what stops the marker vouching for
    // itself — an edit between the mirror sync and the deploy shows up here.
    const verdict = verifyDeployedCommit({
      live,
      repo: { ...healthy, stampParent: "0000000deadbeef0000000000000000000000000" },
    });
    expect(verdict.markerProvenanceOk).toBe(false);
    expect(verdict.problems.map((p) => p.code)).toContain("marker_offset_mismatch");
    expect(verdict.problems[0].detail).toContain("does not sit where stamping would have put it");
  });

  it("catches a stamp commit holding the wrong marker", () => {
    const verdict = verifyDeployedCommit({
      live,
      repo: { ...healthy, buildInfoSource: buildInfo("fb812a6") },
    });
    expect(verdict.markerProvenanceOk).toBe(false);
    expect(verdict.problems.map((p) => p.code)).toContain("marker_offset_mismatch");
  });

  it("catches a matching SHA with a mismatched timestamp", () => {
    const verdict = verifyDeployedCommit({
      live,
      repo: { ...healthy, buildInfoSource: buildInfo("e7e3f80", "2026-01-01T00:00:00-07:00") },
    });
    expect(verdict.markerProvenanceOk).toBe(false);
    expect(verdict.problems.map((p) => p.code)).toContain("marker_offset_mismatch");
  });

  it("warns but still verifies a build deployed off main", () => {
    // Deploying a branch to debug something is legitimate; it just is not
    // reviewable through merged history. Flag it, do not block it.
    const verdict = verifyDeployedCommit({ live, repo: { ...healthy, onMain: false } });
    expect(verdict.markerProvenanceOk).toBe(true);
    expect(verdict.warnings.map((w) => w.code)).toEqual(["not_on_main"]);
  });

  it("fails closed when build-info.ts cannot be read at the stamp commit", () => {
    const verdict = verifyDeployedCommit({ live, repo: { ...healthy, buildInfoSource: "" } });
    expect(verdict.markerProvenanceOk).toBe(false);
    expect(verdict.problems[0].code).toBe("unreadable_build_info");
  });

  it("blocks an otherwise-healthy deploy when the mirror was never pushed", () => {
    // THE 2026-09-11 CASE, driven through the full verdict rather than just the
    // helper: marker provenance, ledger, and the local mirror tree can ALL be
    // clean — this is the one axis that still catches a mirror sync that only
    // exists on the laptop. Lovable deploys origin/main, not the local clone.
    const verdict = verifyDeployedCommit({
      live,
      repo: healthy,
      mirror: {
        commit: "33d676e",
        treeDigest: healthy.sourceTreeDigest,
        localHead: "33d676ea1b2c3d4e5f60718293a4b5c6d7e8f901",
        remoteMain: "0000000deadbeef0000000000000000000000000",
      },
    });
    expect(verdict.markerProvenanceOk).toBe(false);
    expect(verdict.problems.map((p) => p.code)).toContain("mirror_local_not_pushed");
  });

  it("blocks when the mirror's origin/main could not be refreshed", () => {
    const verdict = verifyDeployedCommit({
      live,
      repo: healthy,
      mirror: {
        commit: "33d676e",
        treeDigest: healthy.sourceTreeDigest,
        localHead: "33d676ea1b2c3d4e5f60718293a4b5c6d7e8f901",
        remoteMain: "33d676ea1b2c3d4e5f60718293a4b5c6d7e8f901",
        remoteFetchFailed: true,
      },
    });
    expect(verdict.markerProvenanceOk).toBe(false);
    expect(verdict.problems.map((p) => p.code)).toContain("mirror_fetch_failed");
  });

  it("does not block on a mirror that was actually pushed", () => {
    const verdict = verifyDeployedCommit({
      live,
      repo: healthy,
      mirror: {
        commit: "33d676e",
        treeDigest: healthy.sourceTreeDigest,
        localHead: "33d676ea1b2c3d4e5f60718293a4b5c6d7e8f901",
        remoteMain: "33d676ea1b2c3d4e5f60718293a4b5c6d7e8f901",
      },
    });
    expect(verdict.markerProvenanceOk).toBe(true);
    expect(verdict.problems).toEqual([]);
  });

  it("does not regress existing callers that omit mirror entirely", () => {
    // Every pre-existing call site (and every test above this one) never passed
    // `mirror`. That absence must keep reading as not_run, not as a problem.
    const verdict = verifyDeployedCommit({ live, repo: healthy });
    expect(verdict.markerProvenanceOk).toBe(true);
    expect(verdict.problems).toEqual([]);
  });
});

describe("verifyLedgerConsistency", () => {
  // The ledger and the deploy ref are two records of one fact, written by two
  // git operations. If they can disagree silently, the ledger is not evidence.
  it("accepts the empty initial state", () => {
    expect(verifyLedgerConsistency({ lastEntryBuild: null, refBuild: null })).toEqual([]);
  });

  it("accepts a ref whose full SHA extends the recorded short marker", () => {
    expect(
      verifyLedgerConsistency({
        lastEntryBuild: "e7e3f80",
        refBuild: "e7e3f8098407557e427376029645633507962979",
      }),
    ).toEqual([]);
  });

  it("flags a log entry with no ref", () => {
    const notes = verifyLedgerConsistency({ lastEntryBuild: "e7e3f80", refBuild: null });
    expect(notes.map((n) => n.code)).toEqual(["ledger_ref_divergence"]);
  });

  it("flags a ref with no log entry", () => {
    const notes = verifyLedgerConsistency({ lastEntryBuild: null, refBuild: "e7e3f80" });
    expect(notes.map((n) => n.code)).toEqual(["ledger_ref_divergence"]);
  });

  it("flags a ref and log that name different builds", () => {
    const notes = verifyLedgerConsistency({ lastEntryBuild: "fb812a6", refBuild: "e7e3f80" });
    expect(notes.map((n) => n.code)).toEqual(["ledger_ref_divergence"]);
  });

  it("blocks recording, rather than merely warning", () => {
    // Appending on top of an inconsistent ledger buries the inconsistency under
    // a newer entry, which is the one outcome worse than noticing it late.
    const verdict = verifyDeployedCommit({
      live: okHealth(liveHealth),
      repo: {
        exists: true,
        stampCommit: "2ebd33002d17440a60ec86e25756f7a0700545f2",
        stampParent: "e7e3f8098407557e427376029645633507962979",
        onMain: true,
        buildInfoSource: buildInfo("e7e3f80"),
      },
      ledger: { lastEntryBuild: "fb812a6", refBuild: null },
    });
    expect(verdict.markerProvenanceOk).toBe(false);
    expect(verdict.problems.map((p) => p.code)).toContain("ledger_ref_divergence");
  });
});

describe("verifyMirrorPushed", () => {
  // The full-SHA pair a mirror checkout actually produces: `git rev-parse HEAD`
  // and `git rev-parse origin/main`, after a best-effort fetch.
  const pushed = "33d676ea1b2c3d4e5f60718293a4b5c6d7e8f901";
  const stale = "0000000deadbeef0000000000000000000000000";

  it("reports pushed when local HEAD matches origin/main", () => {
    const result = verifyMirrorPushed({ localHead: pushed, remoteMain: pushed });
    expect(result).toEqual({ status: "pushed", note: null });
  });

  it("reports not_pushed, with a mirror_local_not_pushed note, when they diverge", () => {
    // THE 2026-09-11 CASE: a mirror sync commit made locally and never pushed.
    // The local tree still compares "equal" to canonical (compareSourceTrees has
    // no way to know the commit never left the laptop) — this is the check that
    // catches what that one cannot: does origin/main, what Lovable actually
    // fetches, hold this commit at all?
    const result = verifyMirrorPushed({ localHead: pushed, remoteMain: stale });
    expect(result.status).toBe("not_pushed");
    expect(result.note?.code).toBe("mirror_local_not_pushed");
    expect(result.note?.detail).toContain("has not been pushed");
  });

  it("fails closed with mirror_fetch_failed when the refresh failed, even if a cached ref matches", () => {
    // Codex P1 on #574: after a failed `git fetch`, origin/main still resolves to
    // the cached ref. If that cache equals local HEAD while GitHub has moved on,
    // comparing the two reads "pushed" — a false green on the deploy gate.
    const result = verifyMirrorPushed({ localHead: pushed, remoteMain: pushed, remoteFetchFailed: true });
    expect(result.status).toBe("fetch_failed");
    expect(result.note?.code).toBe("mirror_fetch_failed");
  });

  it("reports not_run — never pushed — when either SHA is unavailable", () => {
    // No mirror path, a mirror clone with no origin/main tracking ref, or a
    // fetch that failed with nothing cached: all legitimate absences, none of
    // which may read as confirmation that the mirror is current.
    expect(verifyMirrorPushed({ localHead: null, remoteMain: pushed })).toEqual({ status: "not_run", note: null });
    expect(verifyMirrorPushed({ localHead: pushed, remoteMain: null })).toEqual({ status: "not_run", note: null });
    expect(verifyMirrorPushed({ localHead: null, remoteMain: null })).toEqual({ status: "not_run", note: null });
  });
});

describe("compareSourceTrees", () => {
  it("reports equality only when both digests are present and match", () => {
    expect(compareSourceTrees({ canonicalTreeDigest: "abc", mirrorTreeDigest: "abc" }).status).toBe("equal");
    expect(compareSourceTrees({ canonicalTreeDigest: "abc", mirrorTreeDigest: "def" }).status).toBe("differs");
  });

  it("reports not_run — never equal — when a digest is missing", () => {
    // No mirror checkout is a legitimate state. Treating "we did not look" as
    // "they matched" is how an unrun step becomes a claimed one.
    expect(compareSourceTrees({ canonicalTreeDigest: "abc", mirrorTreeDigest: null }).status).toBe("not_run");
    expect(compareSourceTrees({ canonicalTreeDigest: null, mirrorTreeDigest: "abc" }).status).toBe("not_run");
    expect(compareSourceTrees({ canonicalTreeDigest: null, mirrorTreeDigest: null }).status).toBe("not_run");
  });
});

