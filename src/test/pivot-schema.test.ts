import { describe, expect, it } from "vitest";
import type { Artifact } from "@/hooks/useThreadArtifacts";
import type { ReviewState } from "@/lib/review";
import {
  BULK_QUEUE_UNAVAILABLE,
  pivotEligibility,
  validatePivotSuggestion,
  type RunnablePivot,
} from "@/lib/pivot-schema";

/**
 * A generated pivot may carry a Run button only after it passes the schema.
 * The production defect: a report parser read a Markdown table row and a
 * footer as pivot targets, and the rail offered them as billed runs.
 */

const valid = {
  id: "email:j.harker@example.com:a1",
  priority: "high",
  action: "Verify email ownership",
  target: "j.harker@example.com",
  targetType: "email",
  reason: "Email discovered via hunter verify. Expand to find linked accounts.",
  sourceArtifactIds: ["a1"],
  basis: "Recorded email from hunter_verify",
  prompt: "Run this high-priority pivot on j.harker@example.com",
  status: "new",
};

const problemsOf = (over: Record<string, unknown>) => {
  const v = validatePivotSuggestion({ ...valid, ...over });
  return v.status === "invalid" ? v.problems.join(" | ") : "";
};

describe("validatePivotSuggestion — strict shape before a Run button", () => {
  it("accepts a well-formed pivot", () => {
    const v = validatePivotSuggestion(valid);
    expect(v.status).toBe("valid");
  });

  it("rejects a Markdown table row as a target (the production defect)", () => {
    expect(problemsOf({ target: "| Review lead | Keith family residence | name |", targetType: "name" })).toMatch(/table cell/);
  });

  it("rejects report boilerplate as a target", () => {
    expect(problemsOf({
      target: "This report was generated by an automated OSINT assistant",
      targetType: "name",
    })).toMatch(/boilerplate/);
  });

  it("rejects a sentence masquerading as a name", () => {
    expect(problemsOf({ target: "Harker appears in none of the reverse address records we pulled", targetType: "name" }))
      .toMatch(/not a name|sentence/);
  });

  it("rejects placeholders and unfilled templates", () => {
    expect(problemsOf({ target: "TBD", targetType: "name" })).toMatch(/placeholder/);
    expect(problemsOf({ target: "<target>", targetType: "username" })).toMatch(/placeholder|username/);
  });

  it("rejects an empty target and an empty reason", () => {
    expect(problemsOf({ target: "   " })).toMatch(/empty/);
    expect(problemsOf({ reason: "" })).toMatch(/reason is empty/);
  });

  it("checks the target against its declared type", () => {
    expect(problemsOf({ target: "not-an-email" })).toMatch(/not an email/);
    expect(problemsOf({ target: "12", targetType: "phone" })).toMatch(/phone/);
    expect(validatePivotSuggestion({ ...valid, target: "northgate-logistics.com", targetType: "domain" }).status).toBe("valid");
    expect(validatePivotSuggestion({ ...valid, target: "James Harker", targetType: "name" }).status).toBe("valid");
  });

  it("rejects a reason that is a table row or only repeats the target", () => {
    expect(problemsOf({ reason: "| confirm | ownership |" })).toMatch(/reason contains a Markdown table cell/);
    expect(problemsOf({ reason: "j.harker@example.com" })).toMatch(/only repeats the target/);
  });

  it("requires every field and refuses unknown ones", () => {
    const { sourceArtifactIds: _drop, ...missing } = valid;
    void _drop;
    expect(validatePivotSuggestion(missing).status).toBe("invalid");
    expect(validatePivotSuggestion({ ...valid, extra: 1 }).status).toBe("invalid");
    expect(validatePivotSuggestion(null).status).toBe("invalid");
  });

  it("keeps the action and target of an invalid suggestion so it can stay visible", () => {
    const v = validatePivotSuggestion({ ...valid, target: "| a | b |", targetType: "name" });
    expect(v.status).toBe("invalid");
    if (v.status === "invalid") {
      expect(v.action).toBe("Verify email ownership");
      expect(v.target).toBe("| a | b |");
    }
  });
});

describe("pivotEligibility — linkage and authority before a run", () => {
  const pivot = (over: Partial<RunnablePivot> = {}): RunnablePivot => {
    const v = validatePivotSuggestion({ ...valid, ...over });
    if (v.status !== "valid") throw new Error(v.problems.join("; "));
    return v.pivot;
  };
  const artifact = (metadata: Record<string, unknown>): Artifact => ({
    id: "a1", kind: "email", value: "j.harker@example.com", confidence: 70, source: "hunter_verify",
    created_at: "2026-09-11T09:00:00Z",
    metadata: { sources: ["hunter_verify"], corroborations: 1, source_class: "provider", ...metadata },
  });
  const ctx = (a: Artifact, review: ReviewState = "new") =>
    ({ artifactsById: new Map([[a.id, a]]), review: () => review });

  it("is runnable when a recorded row proves linkage", () => {
    const e = pivotEligibility(pivot(), ctx(artifact({})));
    expect(e.runnable).toBe(true);
    expect(e.linkage).toBe("linked");
    expect(e.blockers).toEqual([]);
  });

  it("WARNS but does not block a quarantined source — the server now runs it and withholds authority", () => {
    // Changed 2026-09-12 with the switch to promotion quarantine. This used to
    // block, on the grounds that "the server would refuse it anyway" — which
    // is no longer true, and blocking here is what left person-seed runs
    // structurally unable to test the link they were investigating.
    const e = pivotEligibility(pivot(), ctx(artifact({ subject_unlinked: true, subject_unlinked_reason: "name-only query" })));
    expect(e.runnable).toBe(true);
    expect(e.linkage).toBe("unproven");
    expect(e.blockers).toEqual([]);
    // The analyst must still be told what the result will and will not be worth.
    expect(e.warnings.join(" ")).toMatch(/unproven/);
    expect(e.warnings.join(" ")).toMatch(/nothing it finds will count as the subject's evidence/);
  });

  it("an analyst DISMISSAL still blocks — that boundary did not move", () => {
    // Quarantine is a machine claim about provenance; a Dismiss is a human
    // ruling about reality. Re-spending on a struck-out row argues with the
    // analyst, and the server still refuses it at dispatch.
    const e = pivotEligibility(pivot(), ctx(artifact({}), "dismissed"));
    expect(e.runnable).toBe(false);
    expect(e.blockers.join(" ")).toMatch(/dismissed by an analyst/);
  });

  it("warns, without blocking, when the source is marked as a conflict", () => {
    const e = pivotEligibility(pivot(), ctx(artifact({ conflict: true })));
    expect(e.warnings.join(" ")).toMatch(/conflict/);
  });

  it("requires an explicit rerun for a target tools already ran against", () => {
    const e = pivotEligibility(pivot({ status: "searched" }), ctx(artifact({})));
    expect(e.rerun).toBe(true);
    expect(e.warnings.join(" ")).toMatch(/already ran/);
  });

  it("says plainly when a pivot came from report text rather than a recorded row", () => {
    const e = pivotEligibility(pivot({ sourceArtifactIds: [] }), ctx(artifact({})));
    expect(e.linkage).toBe("report");
    expect(e.warnings.join(" ")).toMatch(/report text/);
  });

  it("is never bulk-queueable while no idempotent run contract exists", () => {
    expect(pivotEligibility(pivot(), ctx(artifact({}))).queueable).toBe(false);
    expect(BULK_QUEUE_UNAVAILABLE).toMatch(/idempotency/);
  });
});
