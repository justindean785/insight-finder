/**
 * pivot-schema.ts — may this suggestion become a runnable action?
 *
 * PURE. Every generated pivot passes through here before it is allowed a Run
 * button. The engine (`computePivots`) decides WHICH leads are worth
 * suggesting; this decides whether a suggestion is well-formed enough to act
 * on, and what an analyst must be told before they start it.
 *
 * WHY. Production rendered a runnable "Review lead" whose target was report
 * boilerplate. The report parser reads everything after a "Recommended Next
 * Pivots" heading, including table rows and footers, and falls back to the
 * WHOLE LINE as the target when it finds no identifier — so a sentence became
 * a "name" and a Run button sent it to the agent as a billed pivot. The parser
 * is not the only producer either; any shape that reaches the rail is checked
 * here, at the boundary, rather than trusted.
 *
 * An invalid suggestion is not deleted — it stays visible as "Suggestion needs
 * repair" with the reasons, and it cannot run.
 */
import { z } from "zod";
import type { Artifact } from "@/hooks/useThreadArtifacts";
import type { ReviewState } from "@/lib/review";
import type { DisplayPivot } from "@/lib/pivot-engine";
import { authorityFor } from "@/lib/authority";

export const PIVOT_TARGET_TYPES = ["email", "username", "domain", "url", "ip", "name", "wallet", "phone"] as const;
export type PivotTargetType = (typeof PIVOT_TARGET_TYPES)[number];

/** Report-derived pivots carry a synthetic source id, not an artifact. */
export const REPORT_SOURCE_PREFIX = "report-pivot-";

const BOILERPLATE: { re: RegExp; problem: string }[] = [
  { re: /\|/, problem: "contains a Markdown table cell" },
  { re: /^\s*(?:[-*_]\s*){3,}$/, problem: "is a horizontal rule" },
  { re: /^\s*#{1,6}\s/, problem: "is a Markdown heading" },
  {
    re: /\b(?:generated by|this report|end of (?:the )?report|disclaimer|not legal advice|for informational purposes|all rights reserved|report generated|analyst copy|confidential(?:ity)? notice)\b/i,
    problem: "is report boilerplate",
  },
  { re: /^(?:tbd|n\/?a|none|unknown|null|undefined|todo|placeholder|example|lorem ipsum.*|x{3,}|\?+|-+|…|\.{3})$/i, problem: "is placeholder text" },
  { re: /[<[{]\s*(?:target|value|selector|name|email|username|domain)\s*[>\]}]/i, problem: "is an unfilled template placeholder" },
];

const SHAPE: Record<PivotTargetType, { re: RegExp; problem: string }> = {
  email: { re: /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/, problem: "is not an email address" },
  username: { re: /^@?[\p{L}\p{N}._-]{2,40}$/u, problem: "is not a single username" },
  domain: { re: /^(?=.{3,253}$)(?:[a-z0-9-]+\.)+[a-z]{2,}$/i, problem: "is not a domain name" },
  url: { re: /^https?:\/\/[^\s]+$/i, problem: "is not a URL" },
  ip: { re: /^(?:\d{1,3}\.){3}\d{1,3}$|^[0-9a-f:]{3,39}$/i, problem: "is not an IP address" },
  wallet: { re: /^[A-Za-z0-9]{20,100}$/, problem: "is not a wallet address" },
  phone: { re: /^\+?[\d\s().-]{7,24}$/, problem: "is not a phone number" },
  // A name is a few words. A sentence, a clause or a label with a colon is not.
  name: { re: /^[\p{L}][\p{L}\p{M}'’.\-\s]{0,60}$/u, problem: "is not a name" },
};

const MAX_NAME_WORDS = 6;

const estimateSchema = z.object({
  toolCalls: z.number().int().nonnegative().optional(),
  maxSpendMicroUsd: z.number().nonnegative().optional(),
}).strict();

export const pivotSuggestionSchema = z.object({
  id: z.string().min(1),
  priority: z.enum(["high", "medium", "low"]),
  action: z.string().trim().min(2).max(80),
  target: z.string().trim().min(1, "target is empty").max(160, "target is longer than a selector can be"),
  targetType: z.enum(PIVOT_TARGET_TYPES),
  reason: z.string().trim().min(3, "reason is empty").max(600, "reason is longer than a rationale"),
  sourceArtifactIds: z.array(z.string().min(1)),
  basis: z.string().trim().min(1),
  prompt: z.string().trim().min(1),
  status: z.enum(["new", "searched"]),
  estimate: estimateSchema.optional(),
}).strict().superRefine((p, ctx) => {
  const target = p.target.trim();
  for (const b of BOILERPLATE) {
    if (b.re.test(target)) ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["target"], message: `target ${b.problem}` });
  }
  const shape = SHAPE[p.targetType];
  if (!shape.re.test(target)) ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["target"], message: `target ${shape.problem}` });
  if (p.targetType === "name" && target.split(/\s+/).filter(Boolean).length > MAX_NAME_WORDS) {
    ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["target"], message: `target is ${target.split(/\s+/).length} words — a sentence, not a name` });
  }
  if (p.targetType === "phone" && (target.match(/\d/g) ?? []).length < 7) {
    ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["target"], message: "target has too few digits for a phone number" });
  }
  const reason = p.reason.trim();
  for (const b of BOILERPLATE.slice(0, 4)) {
    if (b.re.test(reason)) ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["reason"], message: `reason ${b.problem}` });
  }
  if (reason.toLowerCase() === target.toLowerCase()) {
    ctx.addIssue({ code: z.ZodIssueCode.custom, path: ["reason"], message: "reason only repeats the target" });
  }
});

/** A suggestion that passed validation. Explicit rather than `z.infer`: this
 *  repo compiles with `strict: false`, under which zod infers every key optional. */
export interface RunnablePivot {
  id: string;
  priority: "high" | "medium" | "low";
  action: string;
  target: string;
  targetType: PivotTargetType;
  reason: string;
  sourceArtifactIds: string[];
  basis: string;
  prompt: string;
  status: "new" | "searched";
  estimate?: { toolCalls?: number; maxSpendMicroUsd?: number };
}

export type PivotValidation =
  | { status: "valid"; pivot: RunnablePivot }
  | { status: "invalid"; problems: string[]; action: string; target: string };

/** Validate an untrusted suggestion. Never throws. */
export function validatePivotSuggestion(input: unknown): PivotValidation {
  const parsed = pivotSuggestionSchema.safeParse(input);
  if (parsed.success) {
    const d = parsed.data;
    // Rebuilt field by field: under `strict: false` zod infers every key
    // optional, so the parsed object is not yet typed as the full shape.
    return {
      status: "valid",
      pivot: {
        id: d.id, priority: d.priority, action: d.action, target: d.target, targetType: d.targetType,
        reason: d.reason, sourceArtifactIds: d.sourceArtifactIds, basis: d.basis, prompt: d.prompt,
        status: d.status, estimate: d.estimate,
      },
    };
  }
  const obj = (input && typeof input === "object" ? input : {}) as Record<string, unknown>;
  const problems = [...new Set(parsed.error.issues.map((i) => i.message))];
  return {
    status: "invalid",
    problems,
    action: typeof obj.action === "string" ? obj.action : "Suggestion",
    target: typeof obj.target === "string" ? obj.target : "",
  };
}

/** Map the engine's display pivot onto the schema's input shape. */
export function pivotSuggestionInput(p: DisplayPivot): Record<string, unknown> {
  const fromReport = p.sourceArtifactId.startsWith(REPORT_SOURCE_PREFIX);
  return {
    id: `${p.type}:${p.value}:${p.sourceArtifactId}`,
    priority: p.priority,
    action: p.actionLabel,
    target: p.value,
    targetType: p.type,
    reason: p.reason || p.why,
    sourceArtifactIds: fromReport ? [] : [p.sourceArtifactId],
    basis: fromReport ? "Recommended in the agent's report text" : `Recorded ${p.type} from ${p.source || "a tool result"}`,
    prompt: p.prompt,
    status: p.status,
  };
}

// ── Eligibility ─────────────────────────────────────────────────────────────

export type PivotLinkage = "linked" | "report" | "unproven";

export interface PivotEligibility {
  /** May be started individually, after the preview. */
  runnable: boolean;
  /** May be put in a bulk queue. False while no idempotent run contract exists. */
  queueable: boolean;
  linkage: PivotLinkage;
  /** Hard stops: the pivot cannot run. */
  blockers: string[];
  /** Shown in the preview; the analyst decides. */
  warnings: string[];
  /** Tools already ran against this target: a rerun must be confirmed explicitly. */
  rerun: boolean;
}

/**
 * Why a batch of pivots cannot be queued. The `osint-agent` endpoint has no
 * run ID or idempotency key, and the chat holds its submit lock for a whole
 * run — so "queue all" sent the first pivot and silently dropped every other
 * one, while marking them all skipped.
 */
export const BULK_QUEUE_UNAVAILABLE =
  "Bulk queue is unavailable: runs have no server-side idempotency contract, so queued pivots could run twice or be dropped. Run pivots one at a time.";

export function pivotEligibility(
  pivot: RunnablePivot,
  ctx: { artifactsById: ReadonlyMap<string, Artifact>; review: (id: string) => ReviewState },
): PivotEligibility {
  const blockers: string[] = [];
  const warnings: string[] = [];
  let linkage: PivotLinkage = "report";

  const sources = pivot.sourceArtifactIds
    .map((id) => ctx.artifactsById.get(id))
    .filter((a): a is Artifact => Boolean(a));

  if (sources.length > 0) {
    // The authority projection is the engine's own decision, read not re-derived.
    const views = sources.map((a) => authorityFor(a, ctx.review(a.id)));
    const allWithheld = views.every((v) => v.state === "quarantined" || v.state === "failed");
    linkage = views.some((v) => v.state !== "quarantined" && v.state !== "failed") ? "linked" : "unproven";
    if (allWithheld) {
      blockers.push(
        views.some((v) => v.state === "failed")
          ? "Its source row was dismissed by an analyst."
          : "Linkage to the subject is unproven (quarantined). The server refuses quarantined selectors.",
      );
    }
    if (views.some((v) => v.state === "conflict")) warnings.push("Its source row is marked as a conflict with the case.");
    if (views.every((v) => v.state === "weak")) warnings.push("It rests only on a low-confidence lead.");
  } else if (pivot.sourceArtifactIds.length > 0) {
    linkage = "unproven";
    warnings.push("Its source row is not in the loaded evidence.");
  } else {
    warnings.push("Suggested by the agent's report text, not by a recorded artifact.");
  }

  const rerun = pivot.status === "searched";
  if (rerun) warnings.push("Tools already ran against this target. Running it again repeats that work and its cost.");

  return { runnable: blockers.length === 0, queueable: false, linkage, blockers, warnings, rerun };
}
